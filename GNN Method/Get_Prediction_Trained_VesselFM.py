    "        if os.path.exists(output_mask_path):\n",
    "            print(f\"Skipping {output_mask_path} → Output already exists.\")\n",
    "            continue\n",
    "        in_path = input_image_path + i\n",
    "        run_inference(model_path, in_path, output_mask_path)\n"
